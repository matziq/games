"use strict";
const fs = require("node:fs");
const path = require("node:path");

const samples = {};
for (const name of ["shot", "blast"]) {
  const wav = fs.readFileSync(path.join(__dirname, "audio", `${name}.wav`));
  if (wav.toString("ascii", 0, 4) !== "RIFF" || wav.toString("ascii", 8, 12) !== "WAVE") {
    throw new Error(`${name}: expected a PCM WAV`);
  }
  let format, data;
  for (let offset = 12; offset + 8 <= wav.length;) {
    const size = wav.readUInt32LE(offset + 4), end = offset + 8 + size;
    if (end > wav.length) throw new Error(`${name}: truncated WAV chunk`);
    const id = wav.toString("ascii", offset, offset + 4);
    if (id === "fmt ") format = wav.subarray(offset + 8, end);
    if (id === "data") data = wav.subarray(offset + 8, end);
    offset = end + (size % 2);
  }
  if (!format || !data || format.readUInt16LE(0) !== 1 ||
      format.readUInt16LE(2) !== 1 || format.readUInt16LE(14) !== 16) {
    throw new Error(`${name}: expected mono 16-bit PCM`);
  }
  samples[name] = { sampleRate: format.readUInt32LE(4), pcm16: data.toString("base64") };
}
const header = `// Generated by pack-audio.cjs; do not edit the encoded audio.
// Pistol: Vincent Sevedge / Tabasco, CC BY 3.0; trimmed, filtered, normalized.
// https://opengameart.org/content/gunshot-sounds
// https://creativecommons.org/licenses/by/3.0/
// Dynamite: Listener, CC0 1.0; sensor removed, downmixed, filtered, normalized.
// https://opengameart.org/content/dynamite-sound-effect
// https://creativecommons.org/publicdomain/zero/1.0/
// These credits describe adapted assets, not endorsement. See audio/LICENSES.md.
`;
const content = header + `(function (root) {\n  "use strict";\n  const samples = ${JSON.stringify(samples)};\n` +
  '  if (typeof module === "object" && module.exports) module.exports = samples;\n' +
  '  else root.AztecSamples = samples;\n})(typeof globalThis !== "undefined" ? globalThis : this);\n';
const destination = path.join(__dirname, "audio-samples.js");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(destination, "utf8").replace(/\r\n/g, "\n") !== content) {
    throw new Error("audio-samples.js is stale. Run node pack-audio.cjs.");
  }
  console.log("Embedded audio matches the maintained WAV assets.");
} else {
  fs.writeFileSync(destination, content);
  console.log(`Packed ${Object.keys(samples).length} offline audio samples.`);
}
