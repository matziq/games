import assert from "node:assert/strict";
import { Chess } from "./chess.js";
import { newTicTacToe, ticResult, playTicTacToe, newCheckers, checkersMoves, checkersResult, playCheckers } from "./rules.js";

const tic = newTicTacToe();
for (const index of [0, 3, 1, 4, 2]) assert.equal(playTicTacToe(tic, index), true);
assert.equal(ticResult(tic), "X wins!");
assert.equal(playTicTacToe(tic, 5), false);
const tie = newTicTacToe();
for (const index of [0,1,2,4,3,5,7,6,8]) assert.equal(playTicTacToe(tie, index), true);
assert.equal(ticResult(tie), "Draw!");

const checkers = newCheckers();
assert.equal(checkersMoves(checkers).length, 7);
assert.equal(playCheckers(checkers, 40, 33), true);
assert.equal(checkers.turn, "b");
const chain = { board: Array(64).fill(""), turn: "r", forced: null, quiet: 0, positions: {} };
for (const [i,p] of [[40,"r"],[33,"b"],[19,"b"],[5,"b"],[42,"r"]]) chain.board[i] = p;
assert.ok(checkersMoves(chain).every(m => m.capture !== null));
assert.equal(playCheckers(chain, 42, 35), false);
assert.equal(playCheckers(chain, 40, 26), true);
assert.equal(chain.forced, 26);
assert.equal(chain.turn, "r");
const restored = JSON.parse(JSON.stringify(chain));
assert.equal(playCheckers(restored, 26, 12), true);
assert.equal(restored.forced, null);
assert.equal(restored.turn, "b");
const crown = { board: Array(64).fill(""), turn: "r", forced: null, quiet: 0, positions: {} };
for (const [i,p] of [[17,"r"],[10,"b"],[12,"b"]]) crown.board[i] = p;
assert.equal(playCheckers(crown, 17, 3), true);
assert.equal(crown.board[3], "R");
assert.equal(crown.turn, "b");
assert.equal(crown.forced, null);
const noMoves = { board: Array(64).fill(""), turn: "r", forced: null, quiet: 0, positions: {} };
noMoves.board[1] = "r"; noMoves.board[62] = "b";
assert.equal(checkersResult(noMoves), "Black wins!");
const draw = newCheckers(); draw.quiet = 80;
assert.match(checkersResult(draw), /Draw/);

const chess = new Chess();
assert.throws(() => chess.move({ from: "e2", to: "e5" }));
for (const move of ["f3", "e5", "g4", "Qh4#"]) chess.move(move);
assert.equal(chess.isCheckmate(), true);
const loaded = new Chess(); loaded.loadPgn(chess.pgn());
assert.equal(loaded.isCheckmate(), true);
const castle = new Chess();
for (const move of ["e4", "e5", "Nf3", "Nc6", "Bc4", "Nf6", "O-O"]) castle.move(move);
assert.equal(castle.get("g1").type, "k");
assert.equal(castle.get("f1").type, "r");
const enPassant = new Chess();
for (const move of ["e4","a6","e5","d5","exd6"]) enPassant.move(move);
assert.equal(enPassant.get("d5"), undefined);
const promote = new Chess("7k/P7/8/8/8/8/8/7K w - - 0 1");
promote.move({ from: "a7", to: "a8", promotion: "n" });
assert.equal(promote.get("a8").type, "n");
const repeat = new Chess();
for (const move of ["Nf3","Nf6","Ng1","Ng8","Nf3","Nf6","Ng1","Ng8"]) repeat.move(move);
const repeatLoaded = new Chess(); repeatLoaded.loadPgn(repeat.pgn());
assert.equal(repeatLoaded.isThreefoldRepetition(), true);
console.log("Board rules passed: wins, draw, required jumps, chaining, crowning, chess specials and saved history.");
